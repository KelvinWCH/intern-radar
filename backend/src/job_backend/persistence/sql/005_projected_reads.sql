CREATE FUNCTION job_read_projection(collection text, source jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $fn$
    SELECT COALESCE(jsonb_object_agg(key,
        CASE WHEN key = 'summary' AND jsonb_typeof(value) = 'string'
            THEN to_jsonb(left(source ->> key, 800)) ELSE value END), '{}'::jsonb)
    FROM jsonb_each(source)
    WHERE key IN (SELECT jsonb_array_elements_text(('{"jobs": ["id", "details_version", "details_updated_at", "deleted_at", "source", "source_type", "review_reason", "external_id", "source_job_id", "company", "title", "application_url", "apply_url", "company_url", "locations", "category", "terms", "sponsorship", "upstream_source", "active", "is_visible", "date_posted", "date_updated", "summary", "source_url", "is_canada_internship", "is_toronto_area", "job_hash", "content_hash", "first_seen_at", "last_seen_at", "last_changed_at"], "job_user_data": ["job_id", "status", "notes", "applied_at", "follow_up_at", "updated_at", "version"], "job_documents": ["id", "job_id", "company", "title", "status", "created_at", "finished_at", "has_resume", "has_cover_letter", "error", "ai_usage"], "import_runs": ["id", "source", "trigger", "status", "started_at", "finished_at", "fetched", "matched", "created", "updated", "unchanged", "error", "task_id", "phase", "items_done", "items_total", "input_tokens", "output_tokens", "cost_usd"], "activity_events": ["id", "kind", "occurred_at"]}'::jsonb) -> collection))
$fn$;

CREATE TABLE job_record_reads (
    collection text COLLATE "C" NOT NULL,
    key text COLLATE "C" NOT NULL,
    data jsonb NOT NULL,
    revision bigint GENERATED BY DEFAULT AS IDENTITY,
    search_body text,
    PRIMARY KEY (collection, key),
    FOREIGN KEY (collection, key) REFERENCES job_records(collection, key) ON DELETE CASCADE
);

CREATE FUNCTION job_refresh_read_projection() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.collection IN ('jobs', 'job_user_data', 'job_documents', 'import_runs', 'activity_events') THEN
        INSERT INTO job_record_reads(collection, key, data, search_body)
        VALUES (NEW.collection, NEW.key, job_read_projection(NEW.collection, NEW.data),
            CASE WHEN NEW.collection = 'jobs'
                THEN job_normalized_text(COALESCE(NEW.data ->> 'raw_description', '')) END)
        ON CONFLICT (collection, key) DO UPDATE
            SET data = EXCLUDED.data, search_body = EXCLUDED.search_body, revision = EXCLUDED.revision;
    END IF;
    RETURN NEW;
END
$fn$;
CREATE TRIGGER job_records_read_projection AFTER INSERT OR UPDATE OF data ON job_records
    FOR EACH ROW EXECUTE FUNCTION job_refresh_read_projection();

INSERT INTO job_record_reads(collection, key, data, search_body)
SELECT collection, key, job_read_projection(collection, data),
    CASE WHEN collection = 'jobs'
        THEN job_normalized_text(COALESCE(data ->> 'raw_description', '')) END
FROM job_records
WHERE collection IN ('jobs', 'job_user_data', 'job_documents', 'import_runs', 'activity_events');

